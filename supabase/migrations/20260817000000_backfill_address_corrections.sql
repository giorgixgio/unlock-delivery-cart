  )
FROM public.orders o
JOIN _address_corrections c ON c.order_number = o.public_order_number
WHERE (o.normalized_city IS DISTINCT FROM c.city)
   OR (o.normalized_address IS DISTINCT FROM c.address);

-- Apply the corrections.
UPDATE public.orders o
SET normalized_city = c.city,
    normalized_address = c.address
FROM _address_corrections c
WHERE c.order_number = o.public_order_number
  AND ((o.normalized_city IS DISTINCT FROM c.city)
    OR (o.normalized_address IS DISTINCT FROM c.address));

-- Recompute the courier zone for any order whose city changed, so shipping
-- label reprints show the correct zone number going forward.
UPDATE public.orders o
SET courier_zone_id = z.zone_id
FROM _address_corrections c
JOIN public.courier_zone_codes z ON lower(trim(z.city_name)) = lower(trim(c.city))
WHERE c.order_number = o.public_order_number
  AND o.normalized_city = c.city;
