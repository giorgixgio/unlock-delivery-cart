-- The previously created (empty) table used a text zone_id and had no branch
-- column; drop it so the operator-provided definition applies cleanly.
DROP TABLE IF EXISTS public.courier_zone_codes;

-- Courier zone codes: maps a delivery locality to the courier's
-- internal zone/route number (printed top-left on the shipping label).
-- Sourced from the operator-provided city list; the same locality can
-- appear once, mapped to its zone.
CREATE TABLE IF NOT EXISTS public.courier_zone_codes (
  id uuid primary key default gen_random_uuid(),
  city_name text not null,
  branch text,
  zone_id integer not null,
  created_at timestamptz not null default now()
);

GRANT SELECT ON public.courier_zone_codes TO authenticated;
GRANT ALL ON public.courier_zone_codes TO service_role;

CREATE UNIQUE INDEX IF NOT EXISTS idx_courier_zone_codes_city_name
  ON public.courier_zone_codes (city_name);

ALTER TABLE public.courier_zone_codes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all access to courier zone codes" ON public.courier_zone_codes;

CREATE POLICY "Staff can read courier zone codes"
  ON public.courier_zone_codes FOR SELECT TO authenticated
  USING (public.is_active_staff(auth.uid()));

CREATE POLICY "Admins can manage courier zone codes"
  ON public.courier_zone_codes FOR ALL TO authenticated
  USING (public.is_active_admin(auth.uid()))
  WITH CHECK (public.is_active_admin(auth.uid()));

